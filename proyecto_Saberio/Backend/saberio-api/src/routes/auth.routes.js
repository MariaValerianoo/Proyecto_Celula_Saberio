const { Router } = require('express');
const controlador = require('../controllers/auth.controller');
const validarRegistro = require('../middlewares/validarRegistro');
const registrarSegundoRol = require('../middlewares/registrarSegundoRol');
const validarLogin = require('../middlewares/validarLogin');
const autenticar = require('../middlewares/autenticar');
const { validarSolicitudRecuperacion, validarRestablecimientoContrasena } = require('../middlewares/validarRecuperacion');
const { DOMINIOS_INSTITUCIONALES } = require('../../config/dominiosInstitucionales');
const router = Router();
router.get('/dominios-institucionales', (req, res) => {
  res.set('Cache-Control', 'no-store');
  res.json({ dominios: DOMINIOS_INSTITUCIONALES });
});
router.use('/admin', require('./admin.routes'));
router.post('/registro', validarRegistro, registrarSegundoRol, controlador.registrar);
router.post('/login', validarLogin, controlador.login);
router.post('/logout', controlador.logout);
router.get('/perfil', autenticar, controlador.obtenerPerfil);
router.put('/perfil', autenticar, controlador.actualizarPerfil);
router.post('/recuperar-contrasena', validarSolicitudRecuperacion, controlador.solicitarRecuperacion);
router.post('/restablecer-contrasena', validarRestablecimientoContrasena, controlador.restablecerContrasena);
module.exports = router;
